package com.infrahub.web.migration;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.MybatisSqlSessionFactoryBuilder;
import com.infrahub.common.context.ApplicationAccess;
import com.infrahub.common.context.UserContextHolder;
import com.infrahub.common.exception.BizException;
import com.infrahub.system.entity.SysUser;
import com.infrahub.system.mapper.SysAccessMapper;
import com.infrahub.system.mapper.SysUserMapper;
import com.infrahub.system.service.SysUserService;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class RoleApplicationAccessIsolatedTest extends MigrationIsolationSupport {
    @Test
    void appliesRoleGrantsWithoutCombiningPermissionsAcrossDifferentApplications() {
        assumeAvailable();
        String database = createOwnedDatabase();
        execute(database, """
                CREATE TABLE sys_role (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_code TEXT, status TEXT);
                CREATE TABLE sys_user_role (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, role_id BIGINT);
                CREATE TABLE sys_permission (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, perm_code TEXT UNIQUE,
                    perm_name TEXT, resource_type TEXT, action TEXT);
                CREATE TABLE sys_role_permission (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_id BIGINT,
                    permission_id BIGINT REFERENCES sys_permission(id));
                CREATE TABLE base_app (id BIGINT PRIMARY KEY, is_deleted BOOLEAN NOT NULL DEFAULT FALSE);
                INSERT INTO sys_role (id, role_code, status) VALUES (1, 'LEGACY', 'ENABLED');
                INSERT INTO sys_permission (id, perm_code) VALUES (1, 'PIPELINE_EXECUTE'), (7, 'SYSTEM_ADMIN');
                """);
        var scripts = copyVersionControlledScripts();
        var previousRelease = flywayConfiguration(database, scripts).baselineVersion("36").target("37").load();
        previousRelease.baseline();
        previousRelease.migrate();
        assertThat(singleValue(database, "SELECT checksum FROM flyway_schema_history WHERE version = '37'"))
                .isEqualTo("-1587168581");
        execute(database, """
                INSERT INTO sys_role_permission (role_id, permission_id)
                SELECT 1, id FROM sys_permission WHERE perm_code = 'APPROVAL_VIEW';
                """);
        var currentRelease = flywayConfiguration(database, scripts).load();
        assertThat(currentRelease.migrate().migrationsExecuted).isEqualTo(1);
        currentRelease.validate();
        assertThat(singleValue(database, "SELECT count(*) FROM sys_permission WHERE perm_code = 'APPROVAL_VIEW'"))
                .isEqualTo("0");
        assertThat(singleValue(database, "SELECT app_scope FROM sys_role WHERE id = 1")).isEqualTo("ALL");
        execute(database, """
                INSERT INTO base_app (id, is_deleted) VALUES (34, false), (35, false), (36, true);
                INSERT INTO sys_role (role_code, status, app_scope) VALUES
                  ('RUNNER', 'ENABLED', 'SELECTED'), ('READER', 'ENABLED', 'SELECTED'), ('DISABLED', 'DISABLED', 'ALL');
                INSERT INTO sys_user_role (user_id, role_id) SELECT 10, id FROM sys_role WHERE role_code <> 'LEGACY';
                INSERT INTO sys_role_permission (role_id, permission_id)
                  SELECT r.id, p.id FROM sys_role r JOIN sys_permission p ON
                    (r.role_code = 'RUNNER' AND p.perm_code IN ('PIPELINE_EXECUTE', 'SYSTEM_ADMIN')) OR
                    (r.role_code = 'READER' AND p.perm_code IN ('PIPELINE_VIEW', 'PIPELINE_DEPLOY')) OR
                    (r.role_code = 'DISABLED' AND p.perm_code = 'SYSTEM_ADMIN');
                INSERT INTO sys_role_app SELECT id, 34 FROM sys_role WHERE role_code = 'RUNNER';
                INSERT INTO sys_role_app SELECT id, 35 FROM sys_role WHERE role_code = 'READER';
                INSERT INTO sys_role_app SELECT id, 36 FROM sys_role WHERE role_code = 'READER';
                """);
        var config = new MybatisConfiguration(new Environment("test", new JdbcTransactionFactory(), dataSourceFor(database)));
        config.addMapper(SysUserMapper.class);
        config.addMapper(SysAccessMapper.class);
        try (var session = new MybatisSqlSessionFactoryBuilder().build(config).openSession(true)) {
            var users = new SysUserService();
            ReflectionTestUtils.setField(users, "baseMapper", session.getMapper(SysUserMapper.class));
            var user = new SysUser();
            user.setId(10L);
            UserContextHolder.set(users.getActiveContext(user));
            assertThat(UserContextHolder.get().getAuthorities()).contains("PIPELINE_EXECUTE", "PIPELINE_VIEW")
                    .doesNotContain("SYSTEM_ADMIN", "ROLE_DISABLED");
            assertThat(ApplicationAccess.allowedApps("PIPELINE_VIEW", "PIPELINE_EXECUTE")).containsExactlyInAnyOrder(34L, 35L);
            assertThat(ApplicationAccess.permits(34L, "PIPELINE_DEPLOY")).isFalse();
            assertThatThrownBy(() -> ApplicationAccess.require(35L, "PIPELINE_EXECUTE")).isInstanceOf(BizException.class);
            session.getMapper(SysAccessMapper.class).clearUserRoles(10L);
            UserContextHolder.set(users.getActiveContext(user));
            assertThat(ApplicationAccess.allowedApps("PIPELINE_EXECUTE")).isEmpty();
        } finally {
            UserContextHolder.clear();
        }
    }
}
