import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { guide } from './guide.mjs';

const input = new URL('./home.html', import.meta.url);
const output = new URL('../site/', import.meta.url);
const repo = 'https://github.com/ty-ux/InfraHub';
const escape = (text) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const url = (root, ...parts) => root + parts.map(({ slug }) => slug + '/').join('') + 'index.html';
const active = (isCurrent) => isCurrent ? ' aria-current="page"' : '';

function layout({ title, description, root, content, home = false, group, page }) {
  const homeUrl = url(root);
  return `<!doctype html>
<!-- Generated by docs/site-src/build.mjs. Edit the source in docs/site-src. -->
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escape(description)}">
  <title>${escape(title)}</title>
  <link rel="stylesheet" href="${root}site.css">
  <script src="${root}guide-nav.js" defer></script>
</head>
<body>
  <a class="skip" href="#main">跳到正文</a>
  <header class="topbar">
    <div class="shell masthead">
      <a class="brand" href="${homeUrl}" aria-label="InfraHub 首页">
        <span class="mark" aria-hidden="true">IH</span>
        InfraHub
      </a>
      <nav aria-label="站点导航">
        <a href="${homeUrl}#architecture">架构</a>
        <a href="${homeUrl}#flow">流程</a>
        <a href="#guide">功能目录</a>
        <a href="${repo}">GitHub <span aria-hidden="true">↗</span></a>
      </nav>
    </div>
  </header>
  <div class="shell guide-layout${home ? ' home-layout' : ''}">
    ${guideNav(root, group, page, home)}
    ${content}
  </div>
  <footer class="shell footer">
    <a href="${homeUrl}">InfraHub 首页</a>
    <a href="${repo}">GitHub 仓库 <span aria-hidden="true">↗</span></a>
  </footer>
</body>
</html>
`;
}

function guideNav(root, group, page, home) {
  return `<aside class="guide-aside" id="guide" tabindex="-1">
    <button type="button" class="guide-menu" aria-expanded="false" aria-controls="guide-nav" hidden>功能目录</button>
    <nav class="guide-nav" aria-label="功能目录" id="guide-nav">
      <h2>功能目录</h2>
      <ul class="guide-tree">
        <li class="guide-home"><a href="${url(root)}"${active(home)}>项目首页</a></li>
        ${guide.map((entry) => `<li class="guide-branch"${entry === group ? ' data-active' : ''}>
          <div class="branch-heading">
            <a href="${url(root, entry)}"${active(entry === page)}>${escape(entry.title)}</a>
            <button type="button" class="branch-toggle" aria-label="${escape(entry.title)}的子模块"
              aria-controls="nav-${entry.slug}" aria-expanded="true" hidden></button>
          </div>
          <ul id="nav-${entry.slug}">
            ${entry.children.map((child) => `<li><a href="${url(root, entry, child)}"${active(child === page)}>${escape(child.title)}</a></li>`).join('\n            ')}
          </ul>
        </li>`).join('\n        ')}
      </ul>
    </nav>
  </aside>`;
}

function directory(entries, linkTo) {
  return `<ul class="directory">
    ${entries.map((entry) => `<li><h3><a href="${linkTo(entry)}">${escape(entry.title)}</a></h3>
      <p>${escape(entry.intro)}</p></li>`).join('\n    ')}
  </ul>`;
}

function list(items, tag) {
  return `<${tag}>${items.map((item) => `<li>${escape(item)}</li>`).join('')}</${tag}>`;
}

function article(root, group, page) {
  const overview = page === group;
  const breadcrumb = overview ? '' : `<li><a href="${url(root, group)}">${escape(group.title)}</a></li>`;
  return `<main id="main" class="guide-main" tabindex="-1">
      <nav class="breadcrumb" aria-label="当前位置">
        <ol><li><a href="${url(root)}#guide">使用指南</a></li>${breadcrumb}<li aria-current="page">${escape(page.title)}</li></ol>
      </nav>
      <article aria-labelledby="page-title">
        <h1 id="page-title">${escape(page.title)}</h1>
        <nav class="page-links" aria-label="本页内容">
          <a href="#introduction">简介</a>
          <a href="#steps">操作步骤</a>
          <a href="#notes">注意事项</a>${overview ? '\n          <a href="#submodules">子模块</a>' : ''}
        </nav>
        <section id="introduction"><h2>简介</h2><p>${escape(page.intro)}</p></section>
        <section id="steps"><h2>操作步骤</h2>${list(page.steps, 'ol')}</section>
        <section id="notes"><h2>注意事项</h2>${list(page.notes, 'ul')}</section>${overview ? `
        <section id="submodules"><h2>子模块</h2>${directory(page.children, (child) => url(root, group, child))}</section>` : ''}
      </article>
    </main>`;
}

async function writePage(relativePath, options) {
  const file = new URL(relativePath, output);
  await mkdir(new URL('./', file), { recursive: true });
  await writeFile(file, layout(options));
}

const home = await readFile(input, 'utf8');
await writePage('index.html', {
  title: 'InfraHub · 架构、交付流程与使用指南',
  description: '了解 InfraHub 整体架构、发布与回滚流程，以及各功能模块的使用方法。',
  root: './',
  content: home,
  home: true,
});

for (const group of guide) {
  for (const page of [group, ...group.children]) {
    const isOverview = page === group;
    const root = isOverview ? '../' : '../../';
    const path = isOverview ? url('', group) : url('', group, page);
    await writePage(path, {
      title: `${page.title} · InfraHub 使用指南`,
      description: page.intro,
      root,
      group,
      page,
      content: article(root, group, page),
    });
  }
}
