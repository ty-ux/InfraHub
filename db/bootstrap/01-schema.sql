    updated_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pipeline_run_pipeline FOREIGN KEY (pipeline_id) REFERENCES pipeline_def(id),
    CONSTRAINT fk_pipeline_run_app FOREIGN KEY (app_id) REFERENCES base_app(id),
    CONSTRAINT fk_pipeline_run_env FOREIGN KEY (env_id) REFERENCES base_env(id),
    CONSTRAINT fk_pipeline_run_version FOREIGN KEY (version_id) REFERENCES release_version(id),
