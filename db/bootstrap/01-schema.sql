    CONSTRAINT fk_pipeline_run_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_pipeline_run_pipeline_created ON pipeline_run (pipeline_id, created_at DESC);
