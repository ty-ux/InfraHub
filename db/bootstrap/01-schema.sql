BEGIN;

CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    display_name VARCHAR(128) NOT NULL,
    email VARCHAR(128),
    mobile VARCHAR(32),
    auth_type VARCHAR(32) NOT NULL DEFAULT 'LOCAL',
    password_hash VARCHAR(256),
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sys_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(64) NOT NULL UNIQUE,
    role_name VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sys_user_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_sys_user_role UNIQUE (user_id, role_id),
    CONSTRAINT fk_sys_user_role_user FOREIGN KEY (user_id) REFERENCES sys_user(id),
    CONSTRAINT fk_sys_user_role_role FOREIGN KEY (role_id) REFERENCES sys_role(id)
);

CREATE TABLE IF NOT EXISTS sys_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perm_code VARCHAR(128) NOT NULL UNIQUE,
    perm_name VARCHAR(128) NOT NULL,
    resource_type VARCHAR(64) NOT NULL,
    action VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sys_role_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_sys_role_permission UNIQUE (role_id, permission_id),
    CONSTRAINT fk_sys_role_permission_role FOREIGN KEY (role_id) REFERENCES sys_role(id),
    CONSTRAINT fk_sys_role_permission_permission FOREIGN KEY (permission_id) REFERENCES sys_permission(id)
);

CREATE TABLE IF NOT EXISTS sys_enum (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enum_type VARCHAR(64) NOT NULL,
    enum_code VARCHAR(64) NOT NULL,
    enum_name VARCHAR(128) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_sys_enum UNIQUE (enum_type, enum_code)
);

CREATE TABLE IF NOT EXISTS sys_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id BIGINT,
    biz_type VARCHAR(64) NOT NULL,
    biz_id BIGINT,
    action VARCHAR(64) NOT NULL,
    before_data JSONB,
    after_data JSONB,
    result VARCHAR(32) NOT NULL,
    ip VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_sys_audit_log_operator FOREIGN KEY (operator_id) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_sys_audit_log_biz ON sys_audit_log (biz_type, biz_id, created_at DESC);

CREATE TABLE IF NOT EXISTS base_app (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_code VARCHAR(64) NOT NULL UNIQUE,
    app_name VARCHAR(128) NOT NULL,
    owner_id BIGINT,
    repo_url VARCHAR(512),
    default_branch VARCHAR(64),
    description VARCHAR(512),
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_base_app_owner FOREIGN KEY (owner_id) REFERENCES sys_user(id),
    CONSTRAINT fk_base_app_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id),
    CONSTRAINT fk_base_app_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_base_app_owner_id ON base_app (owner_id);
CREATE INDEX IF NOT EXISTS idx_base_app_status ON base_app (status);

CREATE TABLE IF NOT EXISTS base_env (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    env_code VARCHAR(32) NOT NULL UNIQUE,
    env_name VARCHAR(64) NOT NULL,
    env_type VARCHAR(32) NOT NULL,
    region VARCHAR(64),
    namespace VARCHAR(128),
    description VARCHAR(512),
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_base_env_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id),
    CONSTRAINT fk_base_env_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_base_env_type_status ON base_env (env_type, status);

CREATE TABLE IF NOT EXISTS base_service (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id BIGINT NOT NULL,
    service_code VARCHAR(64) NOT NULL,
    service_name VARCHAR(128) NOT NULL,
    service_type VARCHAR(32) NOT NULL,
    runtime_type VARCHAR(32) NOT NULL,
    port INTEGER,
    health_check_path VARCHAR(256),
    status VARCHAR(32) NOT NULL DEFAULT 'ENABLED',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_base_service_app_code UNIQUE (app_id, service_code),
    CONSTRAINT fk_base_service_app FOREIGN KEY (app_id) REFERENCES base_app(id),
    CONSTRAINT fk_base_service_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id),
    CONSTRAINT fk_base_service_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_base_service_app_id ON base_service (app_id);
CREATE INDEX IF NOT EXISTS idx_base_service_status ON base_service (status);

CREATE TABLE IF NOT EXISTS pipeline_def (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_code VARCHAR(64) NOT NULL UNIQUE,
    pipeline_name VARCHAR(128) NOT NULL,
    app_id BIGINT NOT NULL,
    trigger_type VARCHAR(32) NOT NULL,
    pipeline_type VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    version INTEGER NOT NULL DEFAULT 1,
    remark VARCHAR(512),
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_pipeline_def_app FOREIGN KEY (app_id) REFERENCES base_app(id),
    CONSTRAINT fk_pipeline_def_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id),
    CONSTRAINT fk_pipeline_def_updated_by FOREIGN KEY (updated_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_pipeline_def_app_id ON pipeline_def (app_id);
CREATE INDEX IF NOT EXISTS idx_pipeline_def_type_enabled ON pipeline_def (pipeline_type, enabled);

CREATE TABLE IF NOT EXISTS pipeline_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id BIGINT NOT NULL,
    stage_name VARCHAR(64) NOT NULL,
    stage_order INTEGER NOT NULL,
    approval_required BOOLEAN NOT NULL DEFAULT FALSE,
    timeout_seconds INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_pipeline_stage_order UNIQUE (pipeline_id, stage_order),
    CONSTRAINT fk_pipeline_stage_pipeline FOREIGN KEY (pipeline_id) REFERENCES pipeline_def(id)
);

CREATE TABLE IF NOT EXISTS pipeline_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL,
    step_name VARCHAR(64) NOT NULL,
    step_type VARCHAR(32) NOT NULL,
    executor_type VARCHAR(32) NOT NULL,
    step_order INTEGER NOT NULL,
    script_content TEXT,
    timeout_seconds INTEGER,
    retry_times INTEGER NOT NULL DEFAULT 0,
    continue_on_fail BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_pipeline_step_order UNIQUE (stage_id, step_order),
    CONSTRAINT fk_pipeline_step_stage FOREIGN KEY (stage_id) REFERENCES pipeline_stage(id)
);

CREATE TABLE IF NOT EXISTS release_artifact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_type VARCHAR(32) NOT NULL,
    artifact_name VARCHAR(256) NOT NULL,
    artifact_uri VARCHAR(1024) NOT NULL,
    checksum VARCHAR(128),
    size_bytes BIGINT,
    repository_type VARCHAR(32),
    repository_project VARCHAR(128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS release_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id BIGINT NOT NULL,
    version_no VARCHAR(64) NOT NULL,
    git_commit VARCHAR(64),
    branch_name VARCHAR(128),
    build_no VARCHAR(64),
    artifact_id BIGINT NOT NULL,
    build_pipeline_run_id BIGINT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_release_version_app_version UNIQUE (app_id, version_no),
    CONSTRAINT fk_release_version_app FOREIGN KEY (app_id) REFERENCES base_app(id),
    CONSTRAINT fk_release_version_artifact FOREIGN KEY (artifact_id) REFERENCES release_artifact(id),
    CONSTRAINT fk_release_version_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_release_version_app_created ON release_version (app_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_release_version_build_run ON release_version (build_pipeline_run_id);

CREATE TABLE IF NOT EXISTS release_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL UNIQUE,
    app_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    env_id BIGINT NOT NULL,
    version_id BIGINT NOT NULL,
    release_type VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL,
    rollback_status VARCHAR(32) NOT NULL DEFAULT 'NOT_ROLLED_BACK',
    rollback_count INTEGER NOT NULL DEFAULT 0,
    last_rollback_at TIMESTAMPTZ,
    risk_level VARCHAR(32),
    approved_by BIGINT,
    approved_at TIMESTAMPTZ,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_release_order_app FOREIGN KEY (app_id) REFERENCES base_app(id),
    CONSTRAINT fk_release_order_service FOREIGN KEY (service_id) REFERENCES base_service(id),
    CONSTRAINT fk_release_order_env FOREIGN KEY (env_id) REFERENCES base_env(id),
    CONSTRAINT fk_release_order_version FOREIGN KEY (version_id) REFERENCES release_version(id),
    CONSTRAINT fk_release_order_approved_by FOREIGN KEY (approved_by) REFERENCES sys_user(id),
    CONSTRAINT fk_release_order_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_release_order_app_env_created ON release_order (app_id, env_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_release_order_status ON release_order (status);

CREATE TABLE IF NOT EXISTS pipeline_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id BIGINT NOT NULL,
    app_id BIGINT NOT NULL,
    env_id BIGINT,
    version_id BIGINT,
    release_id BIGINT,
    trigger_by BIGINT NOT NULL,
    trigger_type VARCHAR(32) NOT NULL,
    run_status VARCHAR(32) NOT NULL,
    start_time TIMESTAMPTZ,
    end_time TIMESTAMPTZ,
    duration_ms BIGINT,
    current_stage VARCHAR(64),
    log_path VARCHAR(512),
    error_message VARCHAR(1000),
