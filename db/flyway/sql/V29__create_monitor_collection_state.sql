-- V29: Create monitor collection state table for host/instance status collection
-- Contract: docs/release/v2-host-instance-status-collection-contract.md Section 3.1
-- Scope: one row per collection target (target_type, target_id). Records last attempt,
--        last successful observation, source, result, consecutive failures, error
--        category/summary and the observation timestamp used as the out-of-order guard.
-- Note: this table never stores an Agent heartbeat. last_heartbeat stays on asset_host /
--       runtime_service_instance and is NOT written by collection (see contract 4.6).

CREATE TABLE IF NOT EXISTS monitor_collection_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(32) NOT NULL,
    target_id BIGINT NOT NULL,
    observer_type VARCHAR(32) NOT NULL DEFAULT 'NONE',
    config_present BOOLEAN NOT NULL DEFAULT FALSE,
    last_source VARCHAR(32) NOT NULL DEFAULT 'NONE',
    last_result VARCHAR(32) NOT NULL DEFAULT 'NONE',
    last_attempt_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    consecutive_failure_count INTEGER NOT NULL DEFAULT 0,
    last_error_category VARCHAR(32),
    last_error_summary VARCHAR(512),
    last_observed_status VARCHAR(32),
    last_observed_health VARCHAR(32),
    observed_at TIMESTAMPTZ,
    discarded_sample_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_monitor_collection_state_target UNIQUE (target_type, target_id)
);

CREATE INDEX IF NOT EXISTS idx_monitor_collection_state_result
    ON monitor_collection_state (last_result, last_success_at DESC);

COMMENT ON TABLE monitor_collection_state IS
    '主机/实例状态采集状态表：每目标一行，记录最近尝试、最近成功观测、来源、结果与失败计数。不存放 Agent 心跳。';
COMMENT ON COLUMN monitor_collection_state.target_type IS
    '目标类型：HOST（对应 asset_host.id）/ SERVICE_INSTANCE（对应 runtime_service_instance.id）';
COMMENT ON COLUMN monitor_collection_state.target_id IS
    '目标主键：target_type=HOST 时为 asset_host.id，target_type=SERVICE_INSTANCE 时为 runtime_service_instance.id';
COMMENT ON COLUMN monitor_collection_state.observer_type IS
    '观测器类型：SSH_PROCESS（SSH 进程诊断）/ NONE（无可用观测器）';
COMMENT ON COLUMN monitor_collection_state.config_present IS
    '该目标当前是否存在可用的启用连接配置：true=存在 enabled 的 SSH 配置';
COMMENT ON COLUMN monitor_collection_state.last_source IS
    '最近一次结果来源：SSH_PROBE（平台主动探测）/ AGENT_REPORT（真实 Agent 上报，当前平台无 Agent，永不写入）/ NONE';
COMMENT ON COLUMN monitor_collection_state.last_result IS
    '最近一次采集结果：SUCCESS / FAILED / SKIPPED_UNCONFIGURED / SKIPPED_UNSUPPORTED / EXPIRED / NONE';
COMMENT ON COLUMN monitor_collection_state.last_attempt_at IS
    '最近一次尝试时刻，包含失败与跳过；不代表采集成功';
COMMENT ON COLUMN monitor_collection_state.last_success_at IS
    '最近一次成功观测时刻；失败与跳过绝不推进该列，是新鲜度判定的唯一依据';
COMMENT ON COLUMN monitor_collection_state.consecutive_failure_count IS
    '连续失败次数；成功或跳过时归零';
COMMENT ON COLUMN monitor_collection_state.last_error_category IS
    '失败类别：CONFIG_MISSING / UNSUPPORTED_TARGET / AUTH_FAILED / NETWORK_TIMEOUT / TARGET_UNREACHABLE / PROBE_ERROR';
COMMENT ON COLUMN monitor_collection_state.last_error_summary IS
    '失败摘要，已脱敏并截断（上限 200 字符），不含密码/私钥/Secret 值';
COMMENT ON COLUMN monitor_collection_state.last_observed_status IS
    '最近一次成功观测得到的运行判定：ONLINE/OFFLINE（主机），RUNNING/STOPPED（实例）';
COMMENT ON COLUMN monitor_collection_state.last_observed_health IS
    '最近一次成功观测得到的健康判定：UP / DOWN / UNKNOWN';
COMMENT ON COLUMN monitor_collection_state.observed_at IS
    '本次样本的观测时刻；写回条件更新的守卫键，迟到旧样本不得覆盖新状态';
COMMENT ON COLUMN monitor_collection_state.discarded_sample_count IS
    '被拒收的迟到样本数：乱序（observed_at 非最新）或目标身份/配置版本失配';