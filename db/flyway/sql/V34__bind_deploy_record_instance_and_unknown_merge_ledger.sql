-- V34: instance attribution for deploy records, and a merge ledger for
-- order-level unknown facts.
--
-- Why these two tables together: both close a hole where the platform had to
-- answer "which execution / which instance does this row belong to" and could
-- only answer it by re-querying a moving set (service + env instances) or by
-- reading back the first row of an order. Both holes are about durable
-- attribution, so they ship in one migration.
--
-- Goal A - runtime_deploy_record_instance
--   runtime_deploy_record belongs to one service/env/host, not to one instance.
--   A service can run several instances on the same host, and instances can be
--   added, removed or re-bound while an execution is running. So a row written
--   at the end of an execution could no longer say which instances that
--   execution actually deployed (the successful pipeline callback re-enumerated
--   service+env and stamped the new version onto instances that were never
--   deployed). The association is written in the same short transaction that
--   inserts the deploy record, so it is a fact recorded at creation time and
--   never back-filled from the order.
--
--   instance_id / host_id deliberately carry NO foreign key: the association is
--   evidence of what was deployed, and it must survive the removal of the
--   instance or of the host. Read paths resolve the current instance row and
--   treat a missing row as "cannot prove" (fail closed), not as "nothing was
--   deployed".
--
-- Goal B - runtime_execution_unknown_merge
--   The V31 dedup index covers (source_type, release order, rollback order,
--   deploy record) and so collapsed every order-level fact of one release order
--   onto a single row. V33 widens the key with plan/batch, but rows merged
--   before V33 was applied have already lost the batch attribution, and the
--   application can still hit the coarser index while V33 is not applied. This
--   table records each such merge (which unresolved fact absorbed which
--   plan/batch), so that:
--     * the absorbed batch is still visible to an operator, and
--     * resolving the absorbing fact can require an explicit acknowledgement
--       instead of silently unblocking a different batch.
--
-- Neither table alters an existing table, so no existing read path (including
-- the application's SELECT * mapping) fails on a database that has not applied
-- this migration yet. Paths that must produce this evidence refuse to run when
-- the table is missing (fail closed), the same way the V32 execution claim does.
--
-- Written but NOT executed by this delivery. Field steps that depend on it stay
-- blocked until the database owner applies V31, V32, V33, V34 in order and
-- restarts the service.
--
-- ASCII only: the baseline V1 corruption came from a lossy charset conversion.

CREATE TABLE IF NOT EXISTS runtime_deploy_record_instance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deploy_record_id BIGINT NOT NULL,
    instance_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    env_id BIGINT NOT NULL,
    host_id BIGINT,
    instance_name VARCHAR(128),
    instance_type VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- One deploy record is produced for exactly one instance; the unique key is
    -- what makes "the instances of this execution" a set with no duplicates.
    CONSTRAINT uk_runtime_deploy_record_instance_record UNIQUE (deploy_record_id),
    CONSTRAINT fk_runtime_deploy_record_instance_record
        FOREIGN KEY (deploy_record_id) REFERENCES runtime_deploy_record(id),
    CONSTRAINT fk_runtime_deploy_record_instance_service
        FOREIGN KEY (service_id) REFERENCES base_service(id),
    CONSTRAINT fk_runtime_deploy_record_instance_env
        FOREIGN KEY (env_id) REFERENCES base_env(id)
);

CREATE INDEX IF NOT EXISTS idx_runtime_deploy_record_instance_instance
    ON runtime_deploy_record_instance (instance_id);

CREATE INDEX IF NOT EXISTS idx_runtime_deploy_record_instance_service_env
    ON runtime_deploy_record_instance (service_id, env_id);

COMMENT ON TABLE runtime_deploy_record_instance IS
    'Instance identity a deploy record was written for, recorded in the same short transaction as the record itself.';
COMMENT ON COLUMN runtime_deploy_record_instance.instance_id IS
    'Observed runtime_service_instance.id. No foreign key on purpose: the instance may be removed later and the association must survive as evidence.';
COMMENT ON COLUMN runtime_deploy_record_instance.host_id IS
    'Host observed at deploy time. Later re-binding of the instance is detected by comparing against the current row, never by rewriting this value.';
COMMENT ON COLUMN runtime_deploy_record_instance.instance_name IS
    'Instance name observed at deploy time, so the record stays readable after the instance row is gone.';

CREATE TABLE IF NOT EXISTS runtime_execution_unknown_merge (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unknown_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    env_id BIGINT NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    release_order_id BIGINT,
    rollback_order_id BIGINT,
    plan_id BIGINT,
    batch_id BIGINT,
    detection_source VARCHAR(32) NOT NULL,
    detection_reason VARCHAR(512) NOT NULL,
    merged_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_runtime_execution_unknown_merge_unknown
        FOREIGN KEY (unknown_id) REFERENCES runtime_execution_unknown(id),
    CONSTRAINT fk_runtime_execution_unknown_merge_release
        FOREIGN KEY (release_order_id) REFERENCES release_order(id),
    CONSTRAINT fk_runtime_execution_unknown_merge_rollback
        FOREIGN KEY (rollback_order_id) REFERENCES release_rollback_order(id)
);

-- One row per absorbed fact. The application writes with ON CONFLICT DO NOTHING,
-- so a repeated registration of the same absorbed batch does not duplicate the
-- ledger entry (the columns are nullable, hence the COALESCE expressions).
CREATE UNIQUE INDEX IF NOT EXISTS uk_runtime_execution_unknown_merge_fact
    ON runtime_execution_unknown_merge (
        unknown_id,
        source_type,
        (COALESCE(plan_id, 0)),
        (COALESCE(batch_id, 0))
    );

CREATE INDEX IF NOT EXISTS idx_runtime_execution_unknown_merge_unknown
    ON runtime_execution_unknown_merge (unknown_id);

COMMENT ON TABLE runtime_execution_unknown_merge IS
    'Ledger of order-level unknown facts that were absorbed by an existing unresolved fact instead of being stored separately.';
COMMENT ON COLUMN runtime_execution_unknown_merge.unknown_id IS
    'The unresolved fact that absorbed this registration; resolving it also covers the plan/batch recorded here.';
COMMENT ON COLUMN runtime_execution_unknown_merge.batch_id IS
    'Batch of the absorbed fact. Its attribution exists only here: the absorbing row keeps its own plan/batch and is never rewritten.';
