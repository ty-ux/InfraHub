-- V32: durable, one-time execution claim for a release run.
--
-- Why a new table: pipeline_run.run_status = 'RUNNING' and release_order.status =
-- 'RUNNING' are observable states, not credentials. Both can be read by another
-- caller between the check and the remote call, so two callers can each believe
-- they own the same execution. A row that stays HELD for the whole remote call,
-- written before the call and released after it, is the only thing that closes
-- that window without holding a database transaction across SSH.
--
-- One row per execution identity, ever. release_order can only leave
-- CREATED/APPROVED once (release_order.status is moved to RUNNING by a
-- conditional update), so a second claim row for the same identity must never
-- exist: that is what makes a duplicate step, a retried pipeline task or a
-- second concurrent run unable to execute again.
--
-- Written but NOT executed by this delivery. Field steps that depend on it stay
-- blocked until the database owner applies it and restarts the service.
--
-- ASCII only: the baseline V1 corruption came from a lossy charset conversion.

CREATE TABLE IF NOT EXISTS release_execution_run_claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_order_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    env_id BIGINT,
    claim_purpose VARCHAR(32) NOT NULL,
    holder_kind VARCHAR(32) NOT NULL,
    holder_token VARCHAR(64) NOT NULL,
    pipeline_run_id BIGINT,
    pipeline_step_run_id BIGINT,
    rollback_order_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'HELD',
    release_outcome VARCHAR(32),
    release_reason VARCHAR(512),
    released_by BIGINT,
    claimed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    released_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_release_execution_run_claim_status
        CHECK (status IN ('HELD', 'RELEASED')),
    CONSTRAINT ck_release_execution_run_claim_purpose
        CHECK (claim_purpose IN ('DEPLOY', 'ROLLBACK')),
    -- A HELD row carries no release facts; a RELEASED row carries all of them.
    -- Without this, a half-written release could look HELD forever or look
    -- released without saying who released it or why.
    CONSTRAINT ck_release_execution_run_claim_release
        CHECK (
            (status = 'HELD'
                AND release_outcome IS NULL
                AND release_reason IS NULL
                AND released_by IS NULL
                AND released_at IS NULL)
            OR
            (status = 'RELEASED'
                AND release_outcome IS NOT NULL
                AND release_reason IS NOT NULL
                AND released_at IS NOT NULL)
        ),
    CONSTRAINT fk_release_execution_run_claim_order
        FOREIGN KEY (release_order_id) REFERENCES release_order(id),
    CONSTRAINT fk_release_execution_run_claim_service
        FOREIGN KEY (service_id) REFERENCES base_service(id),
    CONSTRAINT fk_release_execution_run_claim_env
        FOREIGN KEY (env_id) REFERENCES base_env(id),
    CONSTRAINT fk_release_execution_run_claim_run
        FOREIGN KEY (pipeline_run_id) REFERENCES pipeline_run(id),
    CONSTRAINT fk_release_execution_run_claim_step_run
        FOREIGN KEY (pipeline_step_run_id) REFERENCES pipeline_step_run(id),
    CONSTRAINT fk_release_execution_run_claim_rollback
        FOREIGN KEY (rollback_order_id) REFERENCES release_rollback_order(id),
    CONSTRAINT fk_release_execution_run_claim_released_by
        FOREIGN KEY (released_by) REFERENCES sys_user(id)
);

-- The identity of one execution. Duplicate delivery of the same execution, a
-- second RELEASE_DEPLOY step inside the same pipeline run, and two concurrent
-- runs for one release order all collide on this key. COALESCE keeps the
-- rollback column out of the key for deploy claims, where it is always NULL
-- (a plain UNIQUE would treat two NULLs as distinct and let duplicates in).
CREATE UNIQUE INDEX IF NOT EXISTS uk_release_execution_run_claim_identity
    ON release_execution_run_claim (
        release_order_id,
        claim_purpose,
        (COALESCE(rollback_order_id, 0))
    );

CREATE INDEX IF NOT EXISTS idx_release_execution_run_claim_order_status
    ON release_execution_run_claim (release_order_id, status);

-- Which attempt produced a deploy record. Nullable: records written before this
-- migration, and records written by the paths whose credential is an order or
-- batch conditional update rather than a durable run claim, have no claim.
-- The foreign key is added separately so the table-locking ALTER stays visible.
ALTER TABLE runtime_deploy_record
    ADD COLUMN IF NOT EXISTS execution_claim_id BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_runtime_deploy_record_execution_claim'
    ) THEN
        ALTER TABLE runtime_deploy_record
            ADD CONSTRAINT fk_runtime_deploy_record_execution_claim
            FOREIGN KEY (execution_claim_id) REFERENCES release_execution_run_claim(id);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS idx_runtime_deploy_record_execution_claim
    ON runtime_deploy_record (execution_claim_id);

COMMENT ON TABLE release_execution_run_claim IS
    'One-time execution credential. HELD for the whole remote call; one row per execution identity.';
COMMENT ON COLUMN release_execution_run_claim.status IS
    'HELD while the holder is executing; RELEASED once the holder finished or an operator abandoned it.';
COMMENT ON COLUMN release_execution_run_claim.release_outcome IS
    'COMPLETED / ABANDONED. ABANDONED means an operator gave up the claim; it does not mean the remote stopped.';
COMMENT ON COLUMN runtime_deploy_record.execution_claim_id IS
    'Execution claim that produced this record, when the producing path used a durable run claim.';
