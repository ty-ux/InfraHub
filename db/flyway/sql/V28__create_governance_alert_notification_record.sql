-- V28: Create governance alert notification record table and sequence
-- Contract: docs/release/v2-stage-q-contract.md Section 9.1

-- Sequence for notification number generation (NTF-yyyyMMdd-序号)
CREATE SEQUENCE IF NOT EXISTS seq_notification_record_no START WITH 1 INCREMENT BY 1;

-- Notification record table
CREATE TABLE IF NOT EXISTS release_governance_alert_notification_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_no VARCHAR(32) NOT NULL,
    alert_record_id BIGINT NOT NULL,
    alert_no VARCHAR(32),
    channel_type VARCHAR(32) NOT NULL,
    notification_status VARCHAR(32) NOT NULL,
    target_user_id BIGINT,
    target_user_name VARCHAR(128),
    subject VARCHAR(512),
    content TEXT,
    notify_reason VARCHAR(512),
    evidence_payload TEXT,
    created_by BIGINT,
    created_by_name VARCHAR(128),
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    deleted SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_notification_no UNIQUE (notification_no)
);

-- Indexes per QA requirements
CREATE INDEX IF NOT EXISTS idx_notification_alert_record_id ON release_governance_alert_notification_record (alert_record_id);
CREATE INDEX IF NOT EXISTS idx_notification_status ON release_governance_alert_notification_record (notification_status);
CREATE INDEX IF NOT EXISTS idx_notification_channel_type ON release_governance_alert_notification_record (channel_type);
CREATE INDEX IF NOT EXISTS idx_notification_created_at ON release_governance_alert_notification_record (created_at DESC);

COMMENT ON TABLE release_governance_alert_notification_record IS '告警通知记录表，记录人工确认已提醒的通知。MANUAL_ONLY：不调用真实SMTP/Webhook/短信/IM发送器。';
COMMENT ON COLUMN release_governance_alert_notification_record.notification_no IS '通知编号（唯一），格式 NTF-yyyyMMdd-序号';
COMMENT ON COLUMN release_governance_alert_notification_record.notification_status IS '通知状态：DRAFTED/MANUALLY_CONFIRMED/CANCELLED';
COMMENT ON COLUMN release_governance_alert_notification_record.channel_type IS '通知渠道类型：INTERNAL/EMAIL_DRAFT/WEBHOOK_DRAFT';
