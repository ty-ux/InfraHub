-- V31: durable record for executions whose remote result is unknown.
--
-- Why a new table: runtime_deploy_record has no resolution columns and
-- release_order / release_rollback_order only carry coarse terminal states.
-- The unresolved state and its audited resolution must survive restarts and
-- must not be inferred from free text. sys_audit_log is an audit trail (no
-- uniqueness, retention may be changed), so it cannot be the authoritative
-- state.
--
-- This migration is written but NOT executed by the delivery. Field steps that
-- depend on it stay blocked until the database owner applies it and restarts
-- the service.
--
-- ASCII only: the baseline V1 corruption came from a lossy charset conversion.

CREATE TABLE IF NOT EXISTS runtime_execution_unknown (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL,
    env_id BIGINT NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    release_order_id BIGINT,
    rollback_order_id BIGINT,
    deploy_record_id BIGINT,
    plan_id BIGINT,
    batch_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'UNRESOLVED',
    detection_source VARCHAR(32) NOT NULL,
    detection_reason VARCHAR(512) NOT NULL,
    detected_by BIGINT,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolution_outcome VARCHAR(32),
    resolution_note VARCHAR(1000),
    resolved_by BIGINT,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_runtime_execution_unknown_status
        CHECK (status IN ('UNRESOLVED', 'RESOLVED')),
    CONSTRAINT ck_runtime_execution_unknown_resolution
        CHECK (
            (status = 'UNRESOLVED'
                AND resolution_outcome IS NULL
                AND resolution_note IS NULL
                AND resolved_by IS NULL
                AND resolved_at IS NULL)
            OR
            (status = 'RESOLVED'
                AND resolution_outcome IS NOT NULL
                AND resolution_note IS NOT NULL
                AND resolved_by IS NOT NULL
                AND resolved_at IS NOT NULL)
        ),
    CONSTRAINT fk_runtime_execution_unknown_service
        FOREIGN KEY (service_id) REFERENCES base_service(id),
    CONSTRAINT fk_runtime_execution_unknown_env
        FOREIGN KEY (env_id) REFERENCES base_env(id),
    CONSTRAINT fk_runtime_execution_unknown_release
        FOREIGN KEY (release_order_id) REFERENCES release_order(id),
    CONSTRAINT fk_runtime_execution_unknown_rollback
        FOREIGN KEY (rollback_order_id) REFERENCES release_rollback_order(id),
    CONSTRAINT fk_runtime_execution_unknown_deploy
        FOREIGN KEY (deploy_record_id) REFERENCES runtime_deploy_record(id),
    CONSTRAINT fk_runtime_execution_unknown_detected_by
        FOREIGN KEY (detected_by) REFERENCES sys_user(id),
    CONSTRAINT fk_runtime_execution_unknown_resolved_by
        FOREIGN KEY (resolved_by) REFERENCES sys_user(id)
);

CREATE INDEX IF NOT EXISTS idx_runtime_execution_unknown_service_env
    ON runtime_execution_unknown (service_id, env_id, status);

CREATE INDEX IF NOT EXISTS idx_runtime_execution_unknown_deploy_record
    ON runtime_execution_unknown (deploy_record_id);

-- One unresolved fact per source. Resolved history is append-only and may
-- contain several rows for the same source.
CREATE UNIQUE INDEX IF NOT EXISTS uk_runtime_execution_unknown_unresolved_source
    ON runtime_execution_unknown (
        source_type,
        (COALESCE(release_order_id, 0)),
        (COALESCE(rollback_order_id, 0)),
        (COALESCE(deploy_record_id, 0))
    )
    WHERE status = 'UNRESOLVED';

COMMENT ON TABLE runtime_execution_unknown IS
    'Executions whose remote result could not be proven; unresolved rows block conflicting operations.';
COMMENT ON COLUMN runtime_execution_unknown.status IS
    'UNRESOLVED blocks new conflicting operations; RESOLVED keeps the audited verification result.';
COMMENT ON COLUMN runtime_execution_unknown.resolution_outcome IS
    'REMOTE_EFFECT_APPLIED / REMOTE_EFFECT_NOT_APPLIED / REMOTE_EFFECT_PARTIAL.';
